using System;
using System.Activities;
using System.ComponentModel;
using GridTools.Javelin.Common;
using GridTools.Javelin.ZoweActivities.Helpers;
using GridTools.Javelin.ZoweActivities.Models;

namespace GridTools.Javelin.ZoweActivities.Activities
{
    [DisplayName("Zowe Authenticate (API ML Login)")]
    [Description("Logs into Zowe API Mediation Layer (APIML) or z/OSMF to obtain an API Token (JWT / apimlAuthenticationToken) for subsequent activities")]
    public class ZoweAuthLoginActivity : JavelinNativeActivity
    {
        [Category("1. Connection")]
        [DisplayName("Host / Gateway URL")]
        [Description("Zowe API Gateway or z/OSMF host (e.g. apiml.company.com or https://gateway:10010)")]
        public InArgument<string> Host { get; set; }

        [Category("1. Connection")]
        [DisplayName("Port")]
        [Description("API Gateway HTTPS port (typically 10010 or 10443)")]
        public InArgument<int?> Port { get; set; }

        [Category("1. Connection")]
        [DisplayName("Base Profile Name")]
        [Description("Optional base profile name")]
        public InArgument<string> BaseProfileName { get; set; }

        [Category("2. Credentials")]
        [RequiredArgument]
        [DisplayName("User ID")]
        [Description("Mainframe user ID (RACF / ACF2 / Top Secret)")]
        public InArgument<string> Username { get; set; }

        [Category("2. Credentials")]
        [RequiredArgument]
        [DisplayName("Password")]
        [JavelinPassword]
        [Description("Mainframe user password / passphrase")]
        public InArgument<string> Password { get; set; }

        [Category("3. Options")]
        [DisplayName("Reject Unauthorized SSL (ru)")]
        [DefaultValue(false)]
        public InArgument<bool> RejectUnauthorized { get; set; }

        [Category("3. Options")]
        [DisplayName("Custom Zowe CLI Path")]
        public InArgument<string> CustomZowePath { get; set; }

        [Category("3. Options")]
        [DisplayName("Timeout (Seconds)")]
        [DefaultValue(60)]
        public InArgument<int> TimeoutSeconds { get; set; }

        // --- Outputs ---

        [Category("Output")]
        [DisplayName("API Token (Token Value)")]
        [Description("Authentication token generated by APIML to pass into subsequent Zowe activities")]
        public OutArgument<string> TokenValue { get; set; }

        [Category("Output")]
        [DisplayName("Token Type")]
        [Description("Token type (e.g. apimlAuthenticationToken / Bearer)")]
        public OutArgument<string> TokenType { get; set; }

        [Category("Output")]
        [DisplayName("Raw JSON Response")]
        public OutArgument<string> RawJson { get; set; }

        [Category("Output")]
        [DisplayName("Is Success")]
        public OutArgument<bool> IsSuccess { get; set; }

        [Category("Output")]
        [DisplayName("Error Message")]
        public OutArgument<string> ErrorMessage { get; set; }

        protected override void Execute(NativeActivityContext context)
        {
            try
            {
                base.Execute(context);

                string host = Host.Get(context);
                int? port = Port.Get(context);
                string baseProfile = BaseProfileName.Get(context);
                string user = Username.Get(context);
                string pass = Password.Get(context);
                bool ru = RejectUnauthorized.Get(context);
                string customPath = CustomZowePath.Get(context);
                int timeout = TimeoutSeconds.Get(context);

                if (string.IsNullOrWhiteSpace(user) || string.IsNullOrWhiteSpace(pass))
                    throw new ArgumentException("User ID e Password são obrigatórios para efetuar Login / Obter API Token.");

                var options = new ZoweProfileOptions
                {
                    Host = host,
                    Port = port,
                    BaseProfile = baseProfile,
                    User = user,
                    Password = pass,
                    RejectUnauthorized = ru
                };

                string cmdArgs = "auth login apiml --response-format-json";
                var execResult = ZoweCliHelper.ExecuteCommand(cmdArgs, options, customPath, timeout);

                RawJson.Set(context, execResult.StdOut);
                IsSuccess.Set(context, execResult.Success);

                if (execResult.Success)
                {
                    string json = ZoweOutputParser.ExtractJsonFromCliOutput(execResult.StdOut);
                    string extractedToken = "";
                    string extractedType = "apimlAuthenticationToken";

                    try
                    {
                        var tokenObj = Newtonsoft.Json.Linq.JToken.Parse(json);
                        extractedToken = tokenObj["tokenValue"]?.ToString() ??
                                         tokenObj["data"]?["tokenValue"]?.ToString() ??
                                         tokenObj["token"]?.ToString() ?? "";

                        extractedType = tokenObj["tokenType"]?.ToString() ??
                                        tokenObj["data"]?["tokenType"]?.ToString() ?? "apimlAuthenticationToken";
                    }
                    catch
                    {
                        extractedToken = json;
                    }

                    TokenValue.Set(context, extractedToken);
                    TokenType.Set(context, extractedType);
                    ErrorMessage.Set(context, string.Empty);
                }
                else
                {
                    string formatted = ZoweErrorMessageFormatter.FormatErrorMessage(execResult.FormattedError, "Zowe Authenticate (API ML Login)", host);
                    ErrorMessage.Set(context, formatted);
                    throw new InvalidOperationException(formatted);
                }
            }
            catch (Exception ex)
            {
                string formatted = ZoweErrorMessageFormatter.FormatErrorMessage(ex.Message, "Zowe Authenticate (API ML Login)");
                ErrorMessage.Set(context, formatted);
                IsSuccess.Set(context, false);
                throw;
            }
        }
    }
}
